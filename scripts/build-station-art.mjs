#!/usr/bin/env node
/**
 * Build the bundled station artwork.
 *
 * The website keeps one 1672x941 WebP per station at
 * `KJubilee.com/public/images/stations/<slug>.webp`, addressed by slug rather
 * than carried as a field in the catalog — which is why the generated
 * `stations-data.js` has no image property and the art is easy to miss.
 *
 * Nothing serves those files publicly yet (cdn.kjubilee.com 404s them), so the
 * app bundles its own copy. They are resized on the way in: a 1672px master is
 * ~155 KB and decodes to ~6 MB in memory, which is absurd for a 152pt tile.
 *
 * TWO sizes are emitted, because the two consumers are nowhere near each other:
 *
 *   tiles  — 640px. A 152pt tile at 3x needs ~456px; 640 covers it.
 *   heroes — the master, untouched. The featured hero is FULL-BLEED and taller
 *            than it is wide, so `cover` scales to fill its HEIGHT: ~1155px on a
 *            1080x2400 phone. Against a 360px-tall tile asset that is a 3.2x
 *            upscale, which is exactly as soft as it sounds. Even the 941px
 *            master is stretched ~1.23x, so there is nothing to gain by
 *            shrinking it and everything to lose.
 *
 * Every LIVE station gets a hero copy — 17 files, not 109 — so the bundle
 * pays for sharpness only where it is actually visible.
 *
 * Re-run after the website's artwork changes:
 *   node scripts/build-station-art.mjs
 */
import { readdir, mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const SRC = 'D:/Projects Data/KJubilee.com/public/images/stations';
const OUT = path.join(process.cwd(), 'src/assets/radio/stations');
const HERO_OUT = path.join(process.cwd(), 'src/assets/radio/stations-hero');
/** Tile size: a 152pt tile at 3x needs ~456px. */
const WIDTH = 640;
/** Quality for the hero copies — they are the ones anyone looks at closely. */
const HERO_QUALITY = 88;

/**
 * Which slugs get a full-size copy.
 *
 * Was the featured strip — six stations — because the featured hero was the
 * only full-bleed surface. The STATION PAGE is now full-bleed too, and it can
 * be opened for any station on the dial, so the other eleven live stations were
 * rendering a 640px tile into a ~1420px-tall box: a 3.9x upscale, and it looked
 * it.
 *
 * Live, not all 109: a station with no published day file cannot be tuned, its
 * tiles are `disabled` everywhere, and there is no deep link to its page — so
 * it has no full-bleed surface to be soft on, and 92 unreachable masters would
 * be ~17 MB of bundle for nothing.
 */
const heroWanted = new Set(
  JSON.parse(await readFile(path.join(process.cwd(), 'src/assets/radio/stations.json'), 'utf8'))
    .filter((st) => st.live)
    .map((st) => st.slug),
);

if (!existsSync(SRC)) {
  console.error(`Source artwork not found: ${SRC}`);
  process.exit(1);
}

await rm(OUT, { recursive: true, force: true });
await mkdir(OUT, { recursive: true });
await rm(HERO_OUT, { recursive: true, force: true });
await mkdir(HERO_OUT, { recursive: true });

const files = (await readdir(SRC)).filter((f) => f.endsWith('.webp'));
let bytes = 0;
let heroBytes = 0;

for (const file of files) {
  const buf = await sharp(path.join(SRC, file))
    .resize({ width: WIDTH, withoutEnlargement: true })
    .webp({ quality: 78 })
    .toBuffer();
  await writeFile(path.join(OUT, file), buf);
  bytes += buf.length;

  // The master at its own resolution — no resize, only a re-encode.
  if (heroWanted.has(file.replace(/\.webp$/, ''))) {
    const hero = await sharp(path.join(SRC, file)).webp({ quality: HERO_QUALITY }).toBuffer();
    await writeFile(path.join(HERO_OUT, file), hero);
    heroBytes += hero.length;
  }
}

// Metro cannot build a require() path at runtime, so the slug -> asset mapping
// has to exist as literal requires. Generated rather than hand-kept so adding a
// station to the website is one script run, not an edit here.
const slugs = files.map((f) => f.replace(/\.webp$/, '')).sort();
const heroSlugs = slugs.filter((sl) => heroWanted.has(sl));
const body = `/* GENERATED by scripts/build-station-art.mjs — do not edit by hand.
 * ${slugs.length} station covers, resized from the website's originals.
 *
 * Metro resolves require() paths at build time, so a runtime-built path cannot
 * work; the map below is literal on purpose.
 */
import type { ImageSourcePropType } from 'react-native';

const ART: Record<string, ImageSourcePropType> = {
${slugs.map((s) => `  '${s}': require('./stations/${s}.webp'),`).join('\n')}
};

/**
 * Full-resolution copies for the full-bleed surfaces — the featured hero and
 * the station page — which would otherwise upscale a 640px tile asset by ~4x.
 * Only live stations have one; see heroWanted in the build script.
 */
const HERO: Record<string, ImageSourcePropType> = {
${heroSlugs.map((sl) => `  '${sl}': require('./stations-hero/${sl}.webp'),`).join('\n')}
};

/** Cover art for a station, or undefined when the catalog has none. */
export function stationArt(slug: string): ImageSourcePropType | undefined {
  return ART[slug];
}

/** Hero-resolution art, falling back to the tile copy for a station with none. */
export function heroArt(slug: string): ImageSourcePropType | undefined {
  return HERO[slug] ?? ART[slug];
}
`;
await writeFile(path.join(process.cwd(), 'src/assets/radio/stationArt.ts'), body);

console.log(
  `wrote ${files.length} covers at ${WIDTH}px — ${(bytes / 1048576).toFixed(1)} MB total ` +
    `(${Math.round(bytes / files.length / 1024)} KB mean)`,
);
console.log(
  `wrote ${heroSlugs.length} hero copies at master size — ` +
    `${(heroBytes / 1048576).toFixed(1)} MB total`,
);
